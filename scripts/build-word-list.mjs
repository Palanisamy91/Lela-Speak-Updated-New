#!/usr/bin/env node
/**
 * Builds src/app/lela/word-list.ts: the list of English words the spelling checker knows.
 *
 * The words come from the app's own data (sentences, vocabulary, practice items, conversations in public/data and db.json),
 * so the checker knows the words your learners actually meet. Add a word list of your own to scripts/extra-words.txt
 * (one word per line) if a correct word is ever flagged as a spelling mistake.
 *
 *   node scripts/build-word-list.mjs
 *
 * No dependencies. Safe to run again at any time; it only rewrites word-list.ts.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const counts = new Map();
const TEXT_KEYS = new Set(['en', 'english', 'word', 'answer', 'model', 'accepted', 'answers', 'text', 'example', 'examples', 'sentence', 'sentences', 'say', 'reply', 'hint', 'full', 'blank']);

function addText(s) {
  for (const m of s.matchAll(/[A-Za-z]+(?:'[a-z]+)?/g)) {
    const w = m[0].toLowerCase();
    if (w.includes("'")) continue;
    if (w.length === 1 && w !== 'a' && w !== 'i') continue;
    counts.set(w, (counts.get(w) ?? 0) + 1);
  }
}

function walk(o, keyHint) {
  if (typeof o === 'string') { if (keyHint) addText(o); return; }
  if (Array.isArray(o)) { for (const x of o) walk(x, keyHint); return; }
  if (o && typeof o === 'object') for (const [k, v] of Object.entries(o)) walk(v, TEXT_KEYS.has(k));
}

function files(dir) {
  const out = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...files(p));
    else if (e.name.endsWith('.json')) out.push(p);
  }
  return out;
}

for (const f of files(path.join(root, 'public', 'data'))) {
  try { walk(JSON.parse(fs.readFileSync(f, 'utf8')), false); } catch { /* ignore unreadable files */ }
}
const extra = path.join(root, 'scripts', 'extra-words.txt');
if (fs.existsSync(extra)) for (const w of fs.readFileSync(extra, 'utf8').split(/\s+/)) if (w) counts.set(w.toLowerCase(), (counts.get(w.toLowerCase()) ?? 0) + 3);

const all = [...counts.entries()].sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1));
const common = all.filter(([, c]) => c >= 3).map(([w]) => w).sort();
const rare = all.filter(([, c]) => c < 3).map(([w]) => w).sort();

const wrap = (words) => {
  const lines = [];
  let line = '';
  for (const w of words) {
    if ((line + ' ' + w).length > 150) { lines.push(line); line = w; } else line = line ? `${line} ${w}` : w;
  }
  if (line) lines.push(line);
  return lines.map((l) => `  '${l.replace(/'/g, "\\'")} ' +`).join('\n') + "\n  ''";
};

const out = `// GENERATED by scripts/build-word-list.mjs. Do not edit by hand; run \`node scripts/build-word-list.mjs\` to rebuild.
// ${common.length} common words and ${rare.length} less common words taken from the app's own data.
// Used by the spelling checker (english-lexicon.ts). A word that is not here (and cannot be made from one that is, by adding
// -s, -ed, -ing, -ly ...) is checked as a possible spelling mistake.

export const COMMON_WORDS: string =
${wrap(common)};

export const OTHER_WORDS: string =
${wrap(rare)};
`;
fs.writeFileSync(path.join(root, 'src', 'app', 'lela', 'word-list.ts'), out);
console.log(`word-list.ts written: ${common.length} common + ${rare.length} other words.`);
